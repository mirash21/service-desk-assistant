"""
Утилиты для построения промптов
"""


def build_analysis_prompt(full_context: str) -> str:
    """
    Промпт для анализа входных данных и создания структурированной заявки

    Args:
        full_context: Объединенный контекст (текст, голос, изображения, PDF)

    Returns:
        Промпт для LLM
    """
    return f"""Ты — ассистент сервис-деска ИТ-службы.

На вход ты получаешь объединённый контекст обращения:

{full_context}

Твоя задача — выделить из этих данных:
- user: ФИО или идентификатор пользователя (если есть)
- department: подразделение или команду (если указано)
- summary: краткое описание проблемы (1–2 предложения)
- issue_type: тип проблемы (система, оборудование, сеть, документы, доступ)
- priority: приоритет (low, medium, high)
- raw_notes: дополнительные заметки

Верни ТОЛЬКО валидный JSON с этими полями. Не добавляй пояснений до или после JSON.

Пример:
{{
  "user": "Иванов И.И.",
  "department": "Бухгалтерия",
  "summary": "Не работает принтер Canon",
  "issue_type": "оборудование",
  "priority": "medium",
  "raw_notes": "Пишет ошибку замятия бумаги"
}}"""


def build_user_reply_prompt(ticket_data: str) -> str:
    """
    Промпт для генерации понятного ответа пользователю

    Args:
        ticket_data: JSON-строка с данными заявки

    Returns:
        Промпт для генерации ответа
    """
    return f"""Ты — вежливый ИТ-ассистент компании.

На вход тебе передана заявка в формате JSON:

{ticket_data}

Сформируй короткий текст для пользователя (3–4 предложения максимум):
1. Поблагодари за обращение
2. Кратко повтори суть проблемы простыми словами
3. Укажи приоритет и примерное время реакции:
   - high: в течение 1 часа
   - medium: в течение 4 часов
   - low: в течение 1 рабочего дня
4. Без технического жаргона, дружелюбным тоном

Не включай JSON или технические детали в ответ."""


def build_rag_prompt(query: str, context: str) -> str:
    """
    Промпт для ответа на вопрос с использованием RAG

    Args:
        query: Вопрос пользователя
        context: Релевантный контекст из базы знаний

    Returns:
        Промпт для LLM
    """
    return f"""Ты — ассистент технической поддержки с доступом к базе знаний.

База знаний:
{context}

Вопрос пользователя: {query}

Ответь на вопрос, используя ТОЛЬКО информацию из базы знаний выше.
Если информации недостаточно, честно скажи об этом.
Ответ должен быть кратким (2-3 предложения) и понятным."""


def build_analytics_prompt(tickets_json: str) -> str:
    """
    Промпт для аналитического отчёта по заявкам

    Args:
        tickets_json: JSON-массив заявок за период

    Returns:
        Промпт для генерации отчёта
    """
    return f"""Ты — аналитик сервис-деска.

На вход подаётся список обращений за день:

{tickets_json}

Сформируй структурированный отчёт:

1. Количество обращений по каждому типу проблем
2. Доля высокоприоритетных запросов (%)
3. 2–3 ключевых наблюдения (рост нагрузки, повторяющиеся ошибки)
4. Краткая рекомендация по улучшению процессов (2–3 предложения)

Формат ответа:
## Статистика
[таблица в markdown]

## Наблюдения
[список наблюдений]

## Рекомендации
[текст рекомендаций]"""
