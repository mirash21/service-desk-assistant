#!/usr/bin/env python3
"""
Быстрый старт: Добавление документов в RAG с гарантией качества

Используйте этот скрипт как шаблон для добавления новых документов.
Все проблемы качества будут исправлены автоматически!
"""

from utils.safe_document_manager import SafeDocumentManager


def main():
    """Примеры добавления документов"""
    
    # Инициализация менеджера
    manager = SafeDocumentManager()
    
    print("=" * 80)
    print("БЫСТРЫЙ СТАРТ: ДОБАВЛЕНИЕ ДОКУМЕНТОВ В RAG")
    print("=" * 80)
    
    # ========================================================================
    # Пример 1: Простое добавление одной Q&A пары
    # ========================================================================
    print("\n📝 Пример 1: Добавление одной Q&A пары")
    
    result = manager.add_qa_pair_safe(
        question="Как подключить принтер к компьютеру?",
        answer="""Подключите принтер (печатное устройство, МФУ) через USB кабель или Wi-Fi.
Установите драйверы (driver) с диска или сайта производителя.
Проверьте подключение в Панель управления → Устройства и принтеры.""",
        category="printers",  # опционально, можно не указывать
        auto_fix=True  # ← АВТОМАТИЧЕСКИ ИСПРАВЛЯЕТ ВСЕ ПРОБЛЕМЫ!
    )
    
    if result['success']:
        print(f"✅ Документ успешно добавлен!")
        print(f"   ID: {result.get('document_id', 'N/A')}")
        print(f"   Metadata: {result.get('metadata', {})}")
    else:
        print(f"❌ Ошибка: {result.get('error')}")
    
    # ========================================================================
    # Пример 2: Предварительная проверка перед добавлением
    # ========================================================================
    print("\n📝 Пример 2: Проверка документа перед добавлением")
    
    test_content = """В: Как сбросить пароль?
О: Нажмите Ctrl+Alt+Del. Выберите 'Сменить пароль'."""
    
    validation = manager.validate_before_add(test_content)
    
    print(f"Оценка качества: {validation['score']}/100")
    print(f"Статус: {'✅ Можно добавлять' if validation['success'] else '❌ Нужно исправить'}")
    
    if not validation['success']:
        print("\nРекомендации:")
        print(validation['validation_report'])
    
    # ========================================================================
    # Пример 3: Пакетное добавление нескольких документов
    # ========================================================================
    print("\n📝 Пример 3: Пакетное добавление")
    
    documents = [
        {
            'content': """В: Как настроить Wi-Fi подключение?
О: Откройте настройки сети (network). Выберите вашу Wi-Fi сеть из списка.
Введите пароль (password) от роутера. Дождитесь подключения.""",
            'metadata': {'category': 'network'}
        },
        {
            'content': """В: Что делать если Outlook не отправляет почту?
О: Проверьте настройки SMTP сервера. Убедитесь что порт 587 открыт.
Перезапустите Outlook. Проверьте подключение к интернету.""",
            'metadata': {'category': 'email'}
        },
        {
            'content': """В: Как установить программу на Windows?
О: Скачайте установочный файл (installer) с официального сайта.
Запустите файл .exe. Следуйте инструкциям мастера установки (setup wizard).
Перезагрузите компьютер после установки.""",
            'metadata': {'category': 'software'}
        }
    ]
    
    summary = manager.batch_add_documents_safe(documents, auto_fix=True)
    
    print(f"\nРезультаты пакетной загрузки:")
    print(f"   Всего: {summary['total']}")
    print(f"   Успешно: {summary['success']}")
    print(f"   Ошибки: {summary['failed']}")
    print(f"   Процент успеха: {summary['success_rate']:.1f}%")
    
    # ========================================================================
    # Пример 4: Добавление с ручными metadata
    # ========================================================================
    print("\n📝 Пример 4: Полный контроль над metadata")
    
    content = """Устранение неполадок принтера - Принтер не печатает:

В: Принтер подключен но не печатает, что делать?

О: Выполните диагностику:
• Проверьте очередь печати и удалите зависшие задания
• Перезапустите службу печати (Print Spooler)
• Убедитесь что принтер установлен по умолчанию
• Проверьте уровень картриджей (toner/cartridge)
• Переустановите драйвер (driver) принтера"""
    
    metadata = {
        'type': 'troubleshooting',
        'format': 'qa',
        'category': 'printers',
        'priority': 'high',
        'tags': ['printer', 'not-printing', 'diagnostics']
    }
    
    result = manager.add_document_safe(
        content=content,
        metadata=metadata,
        auto_fix=True  # все равно добавит keywords и проверит качество
    )
    
    if result['success']:
        print(f"✅ Документ добавлен с расширенными metadata")
        print(f"   Final metadata: {result.get('metadata', {})}")
    
    # ========================================================================
    # Пример 5: Обработка длинного документа
    # ========================================================================
    print("\n📝 Пример 5: Автоматическое разбиение длинного документа")
    
    long_content = """В: Полное руководство по настройке сетевого принтера в офисе

О: Настройка сетевого принтера включает несколько этапов:

Этап 1: Физическое подключение
Подключите принтер к сети Ethernet кабелем. Включите принтер. 
Дождитесь загрузки системы. Проверьте индикаторы на панели.

Этап 2: Настройка IP адреса
Откройте меню принтера. Перейдите в Network Settings. 
Выберите Static IP или DHCP. Запишите IP адрес принтера.

Этап 3: Установка на компьютерах
На каждом компьютере откройте Devices and Printers. 
Добавьте новый принтер по IP адресу. Установите драйверы.
Настройте параметры печати по умолчанию.

Этап 4: Тестирование
Распечатайте тестовую страницу с каждого компьютера.
Проверьте качество печати. Настройте двустороннюю печать если нужно.
Проверьте работу сканера если это МФУ."""
    
    result = manager.add_document_safe(
        content=long_content,
        metadata={'category': 'printers', 'type': 'guide'},
        auto_fix=True  # автоматически разобьет на чанки
    )
    
    if result['success']:
        chunks_added = result.get('chunks_added', 1)
        print(f"✅ Длинный документ разбит и добавлен")
        print(f"   Создано чанков: {chunks_added}")
    
    print("\n" + "=" * 80)
    print("ГОТОВО! Все документы добавлены с гарантией качества.")
    print("=" * 80)
    print("\n💡 Советы:")
    print("  • Всегда используйте auto_fix=True")
    print("  • Проверяйте результат через validate_before_add()")
    print("  • Для массового добавления используйте batch_add_documents_safe()")
    print("  • Читайте DOCUMENT_ADDITION_GUIDELINES.md для подробностей")
    print("=" * 80)


if __name__ == '__main__':
    main()
