#!/bin/bash
# Быстрый старт для оптимизации качества RAG базы знаний
# Этот скрипт автоматически выполнит все необходимые проверки и исправления

set -e  # Остановить при ошибке

echo "========================================================================"
echo "БЫСТРЫЙ СТАРТ: ОПТИМИЗАЦИЯ КАЧЕСТВА RAG БАЗЫ ЗНАНИЙ"
echo "========================================================================"
echo ""

# Проверка наличия Python и зависимостей
echo "🔍 Проверка окружения..."
if ! command -v python3 &> /dev/null; then
    echo "❌ Python3 не найден. Установите Python 3.8+"
    exit 1
fi

if [ ! -f ".env" ]; then
    echo "❌ Файл .env не найден. Создайте его с SUPABASE_URL и SUPABASE_KEY"
    exit 1
fi

echo "✅ Окружение проверено"
echo ""

# Шаг 1: Анализ текущего состояния
echo "========================================================================"
echo "ШАГ 1: АНАЛИЗ ТЕКУЩЕГО СОСТОЯНИЯ"
echo "========================================================================"
echo ""
echo "Запуск комплексного анализа..."
python3 scripts/comprehensive_rag_analysis.py

echo ""
read -p "Нажмите Enter чтобы продолжить к исправлению проблем..."

# Шаг 2: Добавление категорий
echo ""
echo "========================================================================"
echo "ШАГ 2: ДОБАВЛЕНИЕ КАТЕГОРИЙ"
echo "========================================================================"
echo ""
echo "Сначала запустим в тестовом режиме (без изменений)..."
python3 scripts/add_categories_to_documents.py

echo ""
read -p "Проверьте результаты. Нажмите Enter чтобы применить изменения, или Ctrl+C для отмены..."

echo "Применение изменений..."
python3 scripts/add_categories_to_documents.py --apply

echo "✅ Категории добавлены"
echo ""

# Шаг 3: Оптимизация длин чанков
echo "========================================================================"
echo "ШАГ 3: ОПТИМИЗАЦИЯ ДЛИН ЧАНКОВ"
echo "========================================================================"
echo ""
echo "Сначала запустим в тестовом режиме (без изменений)..."
python3 scripts/optimize_chunk_lengths.py

echo ""
read -p "Проверьте результаты. Нажмите Enter чтобы применить изменения, или Ctrl+C для отмены..."

echo "Применение изменений..."
python3 scripts/optimize_chunk_lengths.py --apply

echo "✅ Длины чанков оптимизированы"
echo ""

# Шаг 4: Добавление keywords
echo "========================================================================"
echo "ШАГ 4: ДОБАВЛЕНИЕ KEYWORDS"
echo "========================================================================"
echo ""
echo "Сначала запустим в тестовом режиме (без изменений)..."
python3 scripts/add_keywords_to_metadata.py

echo ""
read -p "Проверьте результаты. Нажмите Enter чтобы применить изменения, или Ctrl+C для отмены..."

echo "Применение изменений..."
python3 scripts/add_keywords_to_metadata.py --apply

echo "✅ Keywords добавлены"
echo ""

# Шаг 5: Финальный анализ
echo "========================================================================"
echo "ШАГ 5: ФИНАЛЬНЫЙ АНАЛИЗ"
echo "========================================================================"
echo ""
echo "Запуск финального анализа для проверки улучшений..."
python3 scripts/comprehensive_rag_analysis.py

echo ""
echo "========================================================================"
echo "✅ ВСЕ ШАГИ ВЫПОЛНЕНЫ!"
echo "========================================================================"
echo ""
echo "Рекомендации:"
echo "1. Проверьте отчеты в файлах rag_quality_report_*.txt"
echo "2. Протестируйте поиск в сервис-деск ассистенте"
echo "3. Настройте регулярный анализ (еженедельно/ежемесячно)"
echo ""
echo "Для ручной настройки используйте:"
echo "  python3 scripts/comprehensive_rag_analysis.py     # Анализ"
echo "  python3 scripts/add_categories_to_documents.py    # Категории"
echo "  python3 scripts/optimize_chunk_lengths.py         # Длины чанков"
echo "  python3 scripts/add_keywords_to_metadata.py       # Keywords"
echo ""
echo "Подробная документация: scripts/README_OPTIMIZATION.md"
